import {
  addDoc,
  arrayRemove,
  arrayUnion,
  collection,
  deleteDoc,
  doc,
  getDoc,
  getDocs,
  getFirestore,
  query,
  setDoc,
  where,
} from 'firebase/firestore';

import firebase_app from '@/firebase/config';

const db = getFirestore(firebase_app);

export async function appendFileDataToUser(
  userId: string,
  filesData: { fileIds: string[]; fileName: string; status: string }[]
) {
  const usersRef = collection(db, 'users');
  const docRef = doc(usersRef, userId);

  const value = {
    files: arrayUnion(...filesData.map(file => ({
      fileIds: file.fileIds,
      fileName: file.fileName
    })))
  };

  try {
    await setDoc(docRef, value, { merge: true });
  } catch (e) {
    console.error('Error appending file data:', e);
    throw e;
  }
}

export async function appendChatSpecificFileIds(
  chatId: string,
  files: { fileIds: string[]; fileName: string; status: string }[]
) {
  const result: any[] = [];
  const error: Error[] = [];
  const chatsRef = collection(db, 'chats');
  const chatRef = doc(chatsRef, chatId);

  const value = {
    files: arrayUnion(...files.map(file => ({
      fileIds: file.fileIds,
      fileName: file.fileName
    })))
  };

  try {
    result.push(await setDoc(chatRef, value, { merge: true }));
  } catch (e) {
    error.push(e);
  }

  return { error, result };
}

