import {
  addDoc,
  arrayRemove,
  arrayUnion,
  collection,
  deleteDoc,
  doc,
  getDoc,
  getDocs,
  getFirestore,
  query,
  setDoc,
  where,
} from 'firebase/firestore';

import firebase_app from '@/firebase/config';

const db = getFirestore(firebase_app);

export async function appendFileDataToUser(
  userId: string,
  filesData: Map<string, string>[]
) {
  const usersRef = collection(db, 'users');
  const docRef = doc(usersRef, userId);

  // TODO: Fix this when I fix firebase realtime update, this should be one api call not many
  for (const data of filesData) {
    const value = {
      files: arrayUnion({
        fileName: data['fileName'],
        openAiFileId: data['openAiFileId'],
      }),
    };

    try {
      await setDoc(docRef, value, { merge: true });
    } catch (e) {
      console.log(e);
    }
  }
}

export async function appendDocumentSpecificFileIds(
  documentId: string,
  files: Map<string, string>[]
) {
  const result: any[] = [];
  const error: Error[] = [];
  const documentsRef = collection(db, 'documents');
  const docRef = doc(documentsRef, documentId);

  for (const file of files) {
    const value = {
      files: arrayUnion({
        fileName: file['fileName'],
        openAiFileId: file['openAiFileId'],
      }),
    };

    try {
      result.push(await setDoc(docRef, value, { merge: true }));
    } catch (e) {
      error.push(e);
    }
  }

  return { error, result };
}

