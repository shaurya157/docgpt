export async function saveCurrentDocumentState(
  userId: string,
  documentName: string,
  threadId: string,
  documentVectorStoreId: string,
  document: any,
  documentId?: string
) {
  const documentsRef = collection(db, 'documents');
  let error, result;
  try {
    const value = {
      document: document,
      documentName: documentName,
      documentOwnerId: userId,
      threadId: threadId,
      vectorStoreId: documentVectorStoreId,
    };

    result = documentId
      ? await setDoc(doc(documentsRef, documentId), value, { merge: true })
      : await addDoc(documentsRef, value);
  } catch (e) {
    error = e;
  }

  return { error, result };
}

export async function saveUserTemplate(
  userId: string,
  templateName: string,
  template: any,
  isTemplateOwner: boolean,
  templateId?: string
) {
  const templatesRef = collection(db, "templates");
  let docId, error, result;

  try {
    const value = {
      template,
      templateName,
      templateOwnerId: userId,
    };

    if (templateId && isTemplateOwner) {
      await setDoc(doc(templatesRef, templateId), value, { merge: true });
      docId = templateId; // Since we're updating an existing document, return the provided ID
    } else {
      const docRef = await addDoc(templatesRef, value);
      docId = docRef.id; // Get the autogenerated Firestore ID
      result = docRef;
    }
  } catch (e) {
    error = e;
  }

  return { docId, error, result };
}

